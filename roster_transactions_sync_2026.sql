-- 4. Merge duplicate 2026 roster_entries rows for the same player (keeps the
-- oldest row, folds the others' proj/actual/started/teamId into it).
with ents as (
  select re.id, re.stats, regexp_replace(lower(p.name), '[^a-z0-9]', '', 'g') as nk,
         row_number() over (partition by regexp_replace(lower(p.name), '[^a-z0-9]', '', 'g') order by re.id) as rn
  from roster_entries re
  join players p on p.id = re.player_id
  where re.team_id in (select t.id from teams t join seasons s on s.id = t.season_id and s.year = 2026)
),
g as (
  select nk, (array_agg(id order by rn))[1] as keep_id
  from ents group by nk having count(*) > 1
)
update roster_entries re
set stats = coalesce(re.stats, '{}'::jsonb) || jsonb_build_object(
  'proj', (select coalesce(jsonb_object_agg(x.k, x.v), '{}'::jsonb) from (
      select distinct on (kv.key) kv.key as k, kv.value as v
      from ents e2, jsonb_each(coalesce(e2.stats->'proj', '{}'::jsonb)) kv
      where e2.nk = g.nk
      order by kv.key, e2.rn
    ) x),
  'actual', (select coalesce(jsonb_object_agg(x.k, x.v), '{}'::jsonb) from (
      select distinct on (kv.key) kv.key as k, kv.value as v
      from ents e2, jsonb_each(coalesce(e2.stats->'actual', '{}'::jsonb)) kv
      where e2.nk = g.nk
      order by kv.key, e2.rn
    ) x),
  'started', (select coalesce(jsonb_object_agg(x.k, x.v), '{}'::jsonb) from (
      select distinct on (kv.key) kv.key as k, kv.value as v
      from ents e2, jsonb_each(coalesce(e2.stats->'started', '{}'::jsonb)) kv
      where e2.nk = g.nk
      order by kv.key, e2.rn
    ) x),
  'teamId', (select coalesce(jsonb_object_agg(x.k, x.v), '{}'::jsonb) from (
      select distinct on (kv.key) kv.key as k, kv.value as v
      from ents e2, jsonb_each(coalesce(e2.stats->'teamId', '{}'::jsonb)) kv
      where e2.nk = g.nk
      order by kv.key, e2.rn
    ) x)
)
from g
where re.id = g.keep_id;

with ents as (
  select re.id, regexp_replace(lower(p.name), '[^a-z0-9]', '', 'g') as nk,
         row_number() over (partition by regexp_replace(lower(p.name), '[^a-z0-9]', '', 'g') order by re.id) as rn
  from roster_entries re
  join players p on p.id = re.player_id
  where re.team_id in (select t.id from teams t join seasons s on s.id = t.season_id and s.year = 2026)
)
delete from roster_entries where id in (select id from ents where rn > 1);

-- 5. Roster rows for anyone on a roster in weeks 1-7 who doesn't have one yet
with mem as (
  select regexp_replace(lower(rm.player_name), '[^a-z0-9]', '', 'g') as nk,
         jsonb_object_agg(rm.week::text, t.id::text) as team_map,
         array_agg(rm.week) as weeks,
         (array_agg(t.id order by rm.week desc))[1] as last_team_id
  from roster_membership_2026 rm
  join managers mg on mg.name = rm.manager_name
  join seasons s on s.year = 2026
  join teams t on t.manager_id = mg.id and t.season_id = s.id
  group by 1
)
insert into roster_entries (player_id, team_id, season_id, league_id, stats)
select distinct on (mem.nk) p.id, mem.last_team_id, s.id,
       (select t2.league_id from teams t2 where t2.id = mem.last_team_id), '{}'::jsonb
from mem
join players p on regexp_replace(lower(p.name), '[^a-z0-9]', '', 'g') = mem.nk
cross join (select id from seasons where year = 2026) s
where not exists (
  select 1 from roster_entries re
  join players p2 on p2.id = re.player_id
  where re.team_id in (select t.id from teams t join seasons s on s.id = t.season_id and s.year = 2026) and regexp_replace(lower(p2.name), '[^a-z0-9]', '', 'g') = mem.nk
)
order by mem.nk, p.id;

